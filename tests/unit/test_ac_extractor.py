    def test_replace_generates_new_local_ids(self):
        """Test that new task items have unique local IDs."""
        result = replace_acs_in_adf(None, ["Criterion 1", "Criterion 2"])

        task_list = result["content"][1]
        local_ids = [item["attrs"]["localId"] for item in task_list["content"]]
        assert len(set(local_ids)) == 2  # All unique

    def test_replace_sets_todo_state(self):
        """Test that new task items have TODO state."""
        result = replace_acs_in_adf(None, ["Criterion"])

        task_list = result["content"][1]
        task_item = task_list["content"][0]
        assert task_item["attrs"]["state"] == "TODO"

    def test_replace_with_invalid_acs_items(self):
        """Test that invalid AC items are filtered out."""
        result = replace_acs_in_adf(None, ["Valid", "", None, "  ", "Also valid"])

        task_list = result["content"][1]
        assert len(task_list["content"]) == 2

    def test_replace_preserves_pre_ac_content(self):
        """Test that content before AC section is preserved."""
        existing_adf = {
            "type": "doc",
            "version": 1,
            "content": [
                {
                    "type": "heading",
                    "attrs": {"level": 1},
                    "content": [{"type": "text", "text": "Story Title"}],
                },
                {
                    "type": "paragraph",
                    "content": [{"type": "text", "text": "Story description"}],
                },
                {
                    "type": "heading",
                    "attrs": {"level": 2},
                    "content": [{"type": "text", "text": "Acceptance Criteria"}],
                },
                {
                    "type": "taskList",
                    "attrs": {"localId": "old-id"},
                    "content": [],
                },
            ],
        }

        result = replace_acs_in_adf(existing_adf, ["New criterion"])

        # First two elements should be preserved
