    def test_replace_with_none_and_empty_acs(self):
        """Test replacing with None existing_adf and empty ACs."""
        result = replace_acs_in_adf(None, [])

        assert result["type"] == "doc"
        assert result["version"] == 1
        assert result["content"] == []

    def test_replace_preserves_content_after_ac_section(self):
        """Test that content after AC section is preserved."""
        existing_adf = {
            "type": "doc",
            "version": 1,
            "content": [
                {
                    "type": "heading",
                    "attrs": {"level": 2},
                    "content": [{"type": "text", "text": "Acceptance Criteria"}],
                },
                {
                    "type": "taskList",
                    "attrs": {"localId": "old-id"},
                    "content": [],
                },
                {
                    "type": "paragraph",
                    "content": [
                        {
                            "type": "text",
                            "text": "Generated by Jira AC Assistant",
                            "marks": [{"type": "em"}],
                        }
                    ],
                },
                {
                    "type": "heading",
                    "attrs": {"level": 2},
                    "content": [{"type": "text", "text": "Technical Notes"}],
                },
                {
                    "type": "paragraph",
                    "content": [{"type": "text", "text": "Keep this"}],
                },
            ],
        }

        result = replace_acs_in_adf(existing_adf, ["New criterion"])

        # Find the Technical Notes section
        tech_notes_idx = None
        for i, node in enumerate(result["content"]):
            if node.get("type") == "heading":
                text_content = ""
                for c in node.get("content", []):
                    text_content += c.get("text", "")
                if "Technical Notes" in text_content:
                    tech_notes_idx = i
                    break

        assert tech_notes_idx is not None
        # Content after should be preserved
        after_tech_notes = result["content"][tech_notes_idx + 1]
        assert after_tech_notes["content"][0]["text"] == "Keep this"

    def test_replace_handles_invalid_existing_adf(self):
        """Test handling of invalid existing_adf types."""
        result = replace_acs_in_adf("not a dict", ["Criterion"])

